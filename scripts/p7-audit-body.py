def TBL(headers, rows, ratios, caption=None, font=9.5):
    assert abs(sum(ratios) - 1.0) < 0.01
    widths = [r * AVAIL_W * 0.98 for r in ratios]
    hstyle = S['tbl_h'] if font == 9.5 else ParagraphStyle(
        'TblHs', parent=S['tbl_h'], fontSize=font, leading=font + 3)
    cstyle = ParagraphStyle('TblCs', parent=S['tbl_c'], fontSize=font, leading=font + 3.5)
    data = [[Paragraph('<b>%s</b>' % h, hstyle) for h in headers]]
    for row in rows:
        data.append([Paragraph(str(c), cstyle) for c in row])
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 0 else colors.white))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 10), t]
    if caption:
        out += [Spacer(1, 2), Paragraph(caption, S['caption'])]
    out.append(Spacer(1, 10))
    return out


def STAT(big, label):
    """Metric callout: one big number + label."""
    stat_style = ParagraphStyle('StatBig', fontName='FreeSerif', fontSize=20,
                                leading=24, textColor=ACCENT, alignment=TA_CENTER)
    lab_style = ParagraphStyle('StatLab', fontName='FreeSerif', fontSize=8.5,
                               leading=11, textColor=TEXT_MUTED, alignment=TA_CENTER)
    box = Table([[Paragraph('<b>%s</b>' % big, stat_style)],
                 [Paragraph(label, lab_style)]], colWidths=[AVAIL_W * 0.30])
    box.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('BOX', (0, 0), (-1, -1), 1, ACCENT),
        ('TOPPADDING', (0, 0), (-1, 0), 8),
        ('BOTTOMPADDING', (0, -1), (-1, -1), 8),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))
    wrap = Table([[box]], colWidths=[AVAIL_W])
    wrap.setStyle(TableStyle([('ALIGN', (0, 0), (0, 0), 'CENTER'),
                              ('TOPPADDING', (0, 0), (-1, -1), 0),
                              ('BOTTOMPADDING', (0, 0), (-1, -1), 0)]))
    return [Spacer(1, 8), KeepTogether(wrap), Spacer(1, 10)]


